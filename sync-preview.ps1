# Rebuilds the local Markdown preview styling from index.html.
# Run after every change to index.html:  ./sync-preview.ps1
#
# Outputs:
#   preview.css            all <style> blocks from index.html + a Docsify "vue" theme approximation
#   .crossnote/style.less  Markdown Preview Enhanced: imports preview.css
#   .crossnote/preview.js  Markdown Preview Enhanced: the Docsify plugin scripts from index.html
#   .crossnote/head.html   Markdown Preview Enhanced: loads preview.js
#   MPE only runs <script src> files, and only with the user setting
#   "markdown-preview-enhanced.enablePreviewScripts": true

$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$utf8 = New-Object System.Text.UTF8Encoding($false)
$html = [IO.File]::ReadAllText((Join-Path $root 'index.html'), [Text.Encoding]::UTF8)

# 1. preview.css ------------------------------------------------------------
$base = @'
/* GENERATED by sync-preview.ps1 from index.html. Do not edit; edit index.html and re-run. */

/* Docsify "vue" theme approximation. body.vscode-body = built-in preview only. */
body.vscode-body {
  background: #fff !important; color: #34495e !important;
  font-family: 'Source Sans Pro','Helvetica Neue',Arial,sans-serif !important;
  font-size: 15px !important; line-height: 1.7;
  max-width: 80ch; margin: 0 auto; padding: 30px 15px 40px;
}
h1,h2,h3,h4,h5,h6 { color: #2c3e50; font-weight: 600; border-bottom: none !important; }
h1 { font-size: 2em; margin: 0 0 1rem; }
h2 { font-size: 1.75em; margin: 45px 0 .8em; }
h3 { font-size: 1.5em; margin: 52px 0 1.2em; }
a { color: #42b983; }
strong { color: #2c3e50; }
code { background: #f8f8f8; color: #e96900; border-radius: 2px; padding: 3px 5px; margin: 0 2px; font-family: Roboto Mono, Monaco, courier, monospace; font-size: .8rem; }
pre { background: #f8f8f8 !important; padding: 0 1.4rem; border-radius: 2px; overflow: auto; line-height: 1.5rem; }
pre code { background: transparent; color: inherit; padding: 2em 0; margin: 0; white-space: pre; }
blockquote { color: #858585; border-left: 4px solid #42b983; margin: 2em 0; padding-left: 20px; }
th, td { border: 1px solid #ddd; padding: 6px 13px; }
tr:nth-child(2n) { background: #f8f8f8; }

/* Docsify helpers: ?> = p.warn (green box), !> = p.tip (red note). Classes added by .crossnote/parser.js */
p.warn { background: rgba(66,185,131,.1); border-radius: 2px; padding: 1rem; }
p.tip { background-color: #f8f8f8; border-left: 4px solid #f66; margin: 2em 0; padding: 12px 24px 12px 30px; position: relative; }
p.tip:before { background-color: #f66; border-radius: 100%; color: #fff; content: "!"; font-size: 14px; font-weight: 700;
  line-height: 20px; text-align: center; position: absolute; left: -12px; top: 14px; height: 20px; width: 20px; }

'@
$styles = [regex]::Matches($html, '(?s)<style[^>]*>(.*?)</style>')
if ($styles.Count -eq 0) { throw 'No <style> block found in index.html' }
$css = $base
$i = 0
foreach ($s in $styles) { $i++; $css += "`n/* ---- index.html <style> block $i ---- */`n" + $s.Groups[1].Value.Trim() + "`n" }
[IO.File]::WriteAllText((Join-Path $root 'preview.css'), $css, $utf8)

# 2. .crossnote/style.less --------------------------------------------------
$cn = Join-Path $root '.crossnote'
New-Item -ItemType Directory $cn -Force | Out-Null
# MPE reads style.less once and recompiles only when style.less itself changes,
# not when the imported preview.css changes. The hash line makes style.less change
# whenever the CSS does, so MPE picks it up.
$hash = [BitConverter]::ToString([Security.Cryptography.SHA256]::Create().ComputeHash($utf8.GetBytes($css))).Replace('-','').Substring(0,12)
$less = @"
/* GENERATED by sync-preview.ps1. Do not edit. preview.css hash: $hash */
@import (inline) "../preview.css";
"@ + @'

.markdown-preview.markdown-preview {
  background: #fff; color: #34495e;
  font-family: 'Source Sans Pro','Helvetica Neue',Arial,sans-serif;
  font-size: 15px; line-height: 1.7;
}
'@
[IO.File]::WriteAllText((Join-Path $cn 'style.less'), $less, $utf8)

# 3. .crossnote/preview.js + head.html: inline <script> blocks that define Docsify plugins --
# Docsify calls plugin(hook) and runs hook.doneEach after every render.
# Here a shim collects those callbacks and re-runs them whenever MPE re-renders.
$scripts = [regex]::Matches($html, '(?s)<script>(.*?)</script>') |
  Where-Object { $_.Groups[1].Value -notmatch 'window\.\$docsify' } |
  ForEach-Object { $_.Groups[1].Value.Trim() }
$plugins = [regex]::Match($html, 'plugins\s*:\s*\[([^\]]*)\]').Groups[1].Value.Trim()
$js = @"
// GENERATED by sync-preview.ps1 from index.html. Do not edit.
$($scripts -join "`n`n")

(function () {
  var each = [];
  var hook = { doneEach: function (fn) { each.push(fn); }, init: function () {}, mounted: function () {},
               ready: function () {}, beforeEach: function () {}, afterEach: function () {} };
  [$plugins].forEach(function (p) { if (typeof p === 'function') p(hook, {}); });
  var timer;
  function run() { each.forEach(function (fn) { try { fn(); } catch (e) { console.error(e); } }); }
  function schedule() { clearTimeout(timer); timer = setTimeout(run, 150); }
  document.addEventListener('DOMContentLoaded', function () {
    run();
    // Re-run when MPE replaces the preview content. Ignore changes the plugin makes itself.
    new MutationObserver(function (muts) {
      if (muts.some(function (m) { return !(m.target.closest && m.target.closest('.bp-check-out')); })) schedule();
    }).observe(document.body, { childList: true, subtree: true });
  });
})();
"@
[IO.File]::WriteAllText((Join-Path $cn 'preview.js'), $js, $utf8)
$head = "<!-- GENERATED by sync-preview.ps1. MPE runs only <script src> files, never inline scripts. -->`n<script src=`"/.crossnote/preview.js`"></script>`n"
[IO.File]::WriteAllText((Join-Path $cn 'head.html'), $head, $utf8)

"Synced: $($styles.Count) style block(s), $(@($scripts).Count) script block(s), plugins: [$plugins]"
